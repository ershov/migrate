#!/bin/bash
. "$(dirname "$0")/../lib/step.sh"
step "Inventory this Mac into LOCAL.md" "$@" <<'EOF'
Snapshots this Mac into ~/migrate/inventory and rewrites the generated block of LOCAL.md
(between the BEGIN/END GENERATED markers). Hand-written sections are left alone.
Measuring disk usage takes a few minutes; --no-sizes skips it.
EOF

S="$DATA/inventory"
OUT="$REPO/LOCAL.md"
BEGIN='<!-- BEGIN GENERATED -->'
END='<!-- END GENERATED -->'
SIZES=1
case " $* " in *" --no-sizes "*) SIZES=0 ;; esac
if ! grep -q "^$BEGIN" "$OUT" 2>/dev/null || ! grep -q "^$END" "$OUT"; then
  die "LOCAL.md has no BEGIN/END GENERATED markers; restore it from git."
fi

bash "$BIN/capture.sh" "$S" >/dev/null || exit 1

dflt() { defaults read "$@" 2>/dev/null | tr -s ' \n' ' ' | sed 's/ $//'; }
bullets() { grep -v '^$' | sed 's/^/- /'; }
lines() { wc -l < "$1" 2>/dev/null | tr -d ' '; }
sizes() { sort -rn | awk -v min="$1" '$1 > min {s = $1; $1 = ""; printf "%7.1f G %s\n", s / 1048576, $0}'; }
fence() { echo '```'; }
# keep identifying strings out of the tracked file
sanitize() {
  sed -e "s|$HOME|~|g" -e "s|$(id -un)|\$USER|g" -e "s|$(scutil --get LocalHostName)|\$HOSTNAME|g" |
    if [ -n "$REDACT" ]; then sed -E "s#$REDACT#REDACTED#g"; else cat; fi
}

generate() {
  echo "Generated by \`bin/120-OLD-inventory.sh\` on $(date +%Y-%m-%d). Do not edit inside this block."

  echo; echo "### Machine"; echo
  system_profiler SPHardwareDataType 2>/dev/null | grep -E 'Model Name|Model Identifier|Chip|Memory' | sed -E 's/^ +/- /'
  echo "- macOS $(sw_vers -productVersion) ($(sw_vers -buildVersion)); $(fdesetup status 2>/dev/null | head -1)"
  echo "- User \`\$USER\` (uid $(id -u)), home \`/Users/\$USER\`, login shell \`$(dscl . -read "/Users/$(id -un)" UserShell | awk '{print $2}')\`"
  if nc -z -G 1 localhost 22 >/dev/null 2>&1; then echo "- Remote Login: on"; else echo "- Remote Login: off"; fi
  echo "- Disk: $(df -h /System/Volumes/Data | awk 'NR==2 {print $3 " used of " $2}')"

  echo; echo "### Disk usage"; echo
  if [ "$SIZES" = 1 ]; then
    echo "Home entries over 1 GB:"; echo; fence
    du -sk "$HOME"/* "$HOME"/.[!.]* 2>/dev/null | sizes 1048576
    fence; echo
    echo "\`~/Library/Application Support\` entries over 0.2 GB:"; echo; fence
    du -sk "$HOME/Library/Application Support"/* 2>/dev/null | sizes 209715
    fence
  else
    echo "Skipped (\`--no-sizes\`)."
  fi

  echo; echo "### Homebrew"; echo
  echo "- $(brew --version | head -1) at \`$(brew --prefix)\`"
  echo "- $(lines "$S/brew/formulae.txt") formulae ($(lines "$S/brew/leaves.txt") leaves), $(lines "$S/brew/casks.txt") casks"
  echo "- Taps: $(tr '\n' ' ' < "$S/brew/taps.txt")"
  echo "- Brewfile entries: $(awk '!/^#/ && NF {print $1}' "$S/brew/Brewfile" | sort | uniq -c | awk '{printf "%s %s, ", $1, $2}' | sed 's/, $//')"
  echo "- Services running: $(grep -c started "$S/brew/services.txt")"

  echo; echo "### Applications"; echo
  echo "App Store:"; echo
  awk -F'\t' '$1 == "MAS" {print "- " $2}' "$S/apps/manual-apps.txt"
  echo; echo "Not managed by Homebrew or the App Store (hand-installed or MDM):"; echo
  awk -F'\t' '$1 == "MANUAL" {print "- " $2}' "$S/apps/manual-apps.txt"
  echo; echo "\`~/Applications\`:"; echo
  bullets < "$S/apps/user-applications.txt"

  echo; echo "### MDM and security agents (never copied)"; echo
  grep -iE 'jamf|crowdstrike|falcon|kolide|cloudflare|code42|cisco|okta|nudge|intune|sentinel|zscaler|netskope|tanium|munki|kandji|mosyle' \
    "$S/apps/launchd-system.txt" | sort -u | bullets

  echo; echo "### Toolchains"; echo; fence
  cat "$S/toolchains.txt"
  fence; echo
  for f in "$S"/apps/*-extensions.txt; do
    [ -f "$f" ] && echo "- $(basename "$f" -extensions.txt): $(lines "$f") extensions"
  done

  echo; echo "### Login items"; echo
  bullets < "$S/apps/login-items.txt"
  echo; echo "### User LaunchAgents and crontab"; echo
  bullets < "$S/apps/launchagents-user.txt"
  echo "- crontab entries: $(grep -cvE '^[[:space:]]*(#|$)' "$S/etc/crontab.txt")"

  echo; echo "### Settings"; echo
  echo "- Appearance: $(dflt -g AppleInterfaceStyle)"
  echo "- Languages: $(dflt -g AppleLanguages)"
  echo "- Input sources: $(defaults read com.apple.HIToolbox AppleEnabledInputSources 2>/dev/null | grep -E 'KeyboardLayout Name|Input Mode' | sed -E 's/.*= "?([^";]*)"?;/\1/' | tr '\n' ',' | sed 's/,$//; s/,/, /g')"
  echo "- Dock: autohide=$(dflt com.apple.dock autohide), tilesize=$(dflt com.apple.dock tilesize)"
  echo "- Screenshots: location=$(dflt com.apple.screencapture location)"
  echo "- Default browser: $(defaults read com.apple.LaunchServices/com.apple.launchservices.secure LSHandlers 2>/dev/null | grep -B2 'LSHandlerURLScheme = https;' | grep LSHandlerRoleAll | sed -E 's/.*= "?([^";]*)"?;/\1/')"
  echo "- Per-host: NSStatusItemSpacing=$(defaults -currentHost read -g NSStatusItemSpacing 2>/dev/null), NSStatusItemSelectionPadding=$(defaults -currentHost read -g NSStatusItemSelectionPadding 2>/dev/null), modifier-key remaps: $(defaults -currentHost read -g 2>/dev/null | grep -c 'keyboard.modifiermapping')"
  echo "- Keyboard shortcuts: $(defaults read com.apple.symbolichotkeys AppleSymbolicHotKeys 2>/dev/null | grep -c enabled) symbolic hotkeys; app shortcuts: $(dflt -g NSUserKeyEquivalents)"
  echo "- Preferences: $(find "$HOME/Library/Preferences" -maxdepth 1 -name '*.plist' | wc -l | tr -d ' ') plists, $(find "$HOME/Library/Preferences/ByHost" -name '*.plist' | wc -l | tr -d ' ') per-host"
  echo "- Menu bar items with stored positions: $(lines "$S/statusitems.tsv")"
  echo; echo "Power (\`pmset -g custom\`):"; echo; fence
  grep -E 'Power:| displaysleep| sleep |hibernatemode|lowpowermode' "$S/etc/pmset.txt"
  fence

  echo; echo "### Keychain items that keep copied app profiles logged in"; echo
  bash "$BIN/safe-storage.sh" list | sed 's/.*|/- /'

  echo; echo "### Files holding credentials (names only)"; echo
  for f in .ssh .gnupg .aws .kube .netrc .npmrc .pypirc .docker/config.json .config/gh/hosts.yml .claude.json .codex/auth.json; do
    [ -e "$HOME/$f" ] && echo "- \`~/$f\`"
  done
  # shellcheck disable=SC2016
  find "$HOME" -maxdepth 1 \( -iname '*token*' -o -iname '*secret*' -o -iname '*credential*' -o -iname '*.kdbx' \) | sed 's/.*/- `&`/'
  # shellcheck disable=SC2016
  grep -lE '(TOKEN|API_KEY|SECRET|PASSWORD)[A-Z_]*=' "$HOME/.bashrc" "$HOME/.bash_profile" "$HOME/.profile" "$HOME/.zshrc" "$HOME/.zshenv" 2>/dev/null |
    sed 's/.*/- `&` exports secrets in plain text/'

  echo; echo "### Checks"; echo
  has_fda || echo "- The terminal has no Full Disk Access: the privacy-grant report (\`tcc-*.txt\`) is empty."
  awk -F'\t' '$1 == "CASK-WITHOUT-APP" {print "- Cask registered in Homebrew but app missing: " $2}' "$S/apps/manual-apps.txt"
  [ -x "$RSYNC" ] || echo "- GNU rsync is missing (\`bin/110-OLD-prepare.sh\` installs it)."
  nc -z -G 1 localhost 22 >/dev/null 2>&1 && echo "- Remote Login is on (needed during a migration; turn it off otherwise)."
  echo
}

[ "$SIZES" = 1 ] && echo "measuring disk usage..."
{
  sed -n "1,/^$BEGIN/p" "$OUT"
  generate | sanitize
  sed -n "/^$END/,\$p" "$OUT"
} > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"

say "" "Wrote the generated block of LOCAL.md." \
  "Now work through LOCAL.md: \"How to produce this file\", then sections L1 to L3." \
  "L1 lists what to fix on this Mac before migrating."
finish
